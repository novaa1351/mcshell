#!/bin/sh
# The session's lock screen. One definition, two callers.
#
# $mod+Shift+l runs this, and so does the power menu's Lock Screen button,
# through the daemon and Sway's `exec`. Both have to put up the same screen,
# and the same string written into two files eventually will not.
#
# WHY THIS IS A SCRIPT AND NOT A ONE-LINER
#
# A lock program draws almost nothing: swaylock draws a colour and a ring,
# hyprlock a password box. Neither draws a screen. That is fine once you know
# what you are looking at, and useless the first time you meet it. It was met
# for the first time on 2026-09-06: a blank navy screen, a green circle when a
# key was pressed, and twenty-six minutes later the power button. The journal
# settled what happened — `pam_unix(swaylock:auth)` logs every attempt, and
# there was not one, so swaylock was never handed a password to check. The
# lock worked perfectly and said nothing about how to leave it.
#
# So the screen is drawn here, into the background image every route can
# display: `lockscreen.py` renders Minecraft's Direct Connection screen out of
# the installed client jar, and the lock program draws its one widget into the
# hole left for it.
#
# WHY HYPRLOCK IS FIRST
#
# swaylock has no password echo of any kind — no asterisks, no dots, no
# character count. Its ring is the whole of its feedback, and a static PNG
# cannot react to a keystroke. hyprlock draws a real input field with a dot
# per character, and is themeable enough to be given TextFieldWidget's own two
# rectangles, so the field in the picture becomes a field you can watch
# yourself type into. Both lock through `ext-session-lock-v1` and both check
# the password with PAM; nothing about the credentials rail moves.
#
# ESCAPE HATCH: if the lock ever will not let you back in, Ctrl+Alt+F2 gets a
# TTY. `loginctl terminate-session` from there ends the session and returns to
# GDM. Do NOT kill the lock program — the compositor holds the session lock,
# so a dead lock client leaves it locked with nothing drawing on it.

set -eu

here=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)

IMAGE="${XDG_RUNTIME_DIR:-/tmp}/mcshell-lock.png"
CONFIG="${XDG_RUNTIME_DIR:-/tmp}/mcshell-hyprlock.conf"
PROMPT="Type your password and press Enter"
IDENTITY="$(id -un)@$(uname -n)"

# The output's own pixels, so nothing is scaled and nothing is blurred.
geometry() {
	swaymsg -t get_outputs -r 2>/dev/null | python3 -c '
import json, sys
for output in json.load(sys.stdin):
    if not output.get("active"):
        continue
    mode = output.get("current_mode") or {}
    if mode.get("width") and mode.get("height"):
        print(mode["width"], mode["height"])
        break
else:
    raise SystemExit(1)
' 2>/dev/null
}

WIDTH=1920
HEIGHT=1080
if size=$(geometry); then
	WIDTH=${size% *}
	HEIGHT=${size#* }
fi

# Shared by every swaylock route below. Idle-visible above all: a lock screen
# that draws nothing until you touch it is indistinguishable from a machine
# that has hung, which is exactly how this went wrong the first time.
COMMON="--indicator-idle-visible --show-failed-attempts --indicator-caps-lock
--key-hl-color 8ab4f8 --bs-hl-color d08770
--ring-ver-color 8ab4f8 --ring-wrong-color d05050
--line-color 00000000 --separator-color 00000000"

# `lockscreen.py` prints `NAME=<integer>` a line and nothing else, so this is
# an eval over our own arithmetic rather than over anything from outside.
layout() {
	"$here/lockscreen.py" --width "$WIDTH" --height "$HEIGHT" \
		--out "$IMAGE" --secondary "$IDENTITY" "$@" 2>/dev/null
}

# --- 1. Minecraft's screen, with a field you can type into -------------------
# The picture leaves the text field out and hyprlock draws a real one in its
# place, coloured as TextFieldWidget's own two rectangles: a one-pixel white
# border and black inside it, square corners, square dots. Failure is said in
# colour rather than in prose — the outline goes red — because there is no
# Minecraft font on the machine to say it in, and a sentence set in DejaVu
# under a screen made of Minecraft's own pixels is the tell.
if command -v hyprlock >/dev/null 2>&1 && geom=$(layout --no-field); then
	eval "$geom"
	OFFSET=$((SCREEN_H / 2 - (FIELD_Y + FIELD_H / 2)))
	cat >"$CONFIG" <<EOF
# Generated by session/lock.sh. Edit that, not this.
general {
    hide_cursor = true
    ignore_empty_input = true
}

background {
    monitor =
    path = $IMAGE
    color = rgb(140f0c)
}

input-field {
    monitor =
    size = $FIELD_W, $FIELD_H
    position = 0, $OFFSET
    halign = center
    valign = center

    rounding = 0
    outline_thickness = $SCALE
    outer_color = rgb(ffffff)
    inner_color = rgb(000000)
    check_color = rgb(8ab4f8)
    fail_color = rgb(d05050)
    capslock_color = rgb(ffd76a)

    font_color = rgb(e0e0e0)
    font_size = $FONT_SIZE
    dots_size = 0.3
    dots_spacing = 0.3
    dots_center = false
    dots_rounding = 0

    fade_on_empty = false
    placeholder_text =
    fail_text =
}
EOF
	exec hyprlock --config "$CONFIG"
fi

# --- 2. The same screen, with swaylock's ring for a cursor -------------------
# swaylock cannot draw a field, so the picture keeps the one it drew and the
# ring goes inside it, where it reads as that field's cursor: lighting per
# keystroke, blue while verifying, red when wrong. No echo, but not silence.
if geom=$(layout); then
	eval "$geom"
	# shellcheck disable=SC2086
	exec swaylock -f -c 140f0c -i "$IMAGE" --scaling fill $COMMON \
		--indicator-x-position "$RING_X" --indicator-y-position "$RING_Y" \
		--indicator-radius "$RING_RADIUS" --indicator-thickness "$RING_THICKNESS" \
		--font-size "$FONT_SIZE" \
		--ring-color 6a7aa8 --ring-clear-color 6a7aa8 \
		--inside-color 00000000 --inside-ver-color 00000000 \
		--inside-wrong-color 00000000 --inside-clear-color 00000000 \
		--text-color ffffff --text-ver-color ffffff \
		--text-wrong-color ff8080 --text-clear-color ffffff
fi

# --- 3. A plain screen that at least says what to do -------------------------
COLOUR=1a1a2e
POINT=$((HEIGHT / 34))
[ "$POINT" -lt 18 ] && POINT=18
RADIUS=$((HEIGHT / 12))
[ "$RADIUS" -lt 60 ] && RADIUS=60
OFFSET=$((RADIUS + POINT * 3))

FONT=DejaVu-Sans
magick -list font 2>/dev/null | grep -q "Font: $FONT$" || FONT=sans-serif

if command -v magick >/dev/null 2>&1 && magick -size "${WIDTH}x${HEIGHT}" "xc:#$COLOUR" \
	-font "$FONT" -gravity center \
	-fill "#7d7d9c" -pointsize "$((POINT * 4 / 5))" -annotate "+0-$OFFSET" "$IDENTITY" \
	-fill "#e6e6f0" -pointsize "$POINT" -annotate "+0+$OFFSET" "$PROMPT" \
	"$IMAGE" 2>/dev/null; then
	# shellcheck disable=SC2086
	exec swaylock -f -c "$COLOUR" -i "$IMAGE" --scaling fill $COMMON \
		--indicator-radius "$RADIUS" --indicator-thickness 8 --font-size "$POINT" \
		--ring-color 4a5a8a \
		--inside-color 1a1a2ecc --inside-ver-color 1a1a2ecc --inside-wrong-color 1a1a2ecc \
		--text-color e6e6f0 --text-ver-color e6e6f0 --text-wrong-color e6e6f0
fi

# --- 4. Bare, and still locked ----------------------------------------------
# shellcheck disable=SC2086
exec swaylock -f -c "$COLOUR" $COMMON --ring-color 4a5a8a
